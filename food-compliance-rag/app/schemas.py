"""
Pydantic schemas for request / response validation.
"""

from __future__ import annotations

from typing import Optional
from uuid import UUID
from datetime import datetime

from pydantic import BaseModel, Field


# ── Documents ────────────────────────────────────────────────

class DocumentOut(BaseModel):
    id: UUID
    filename: str
    title: Optional[str] = None
    source_url: Optional[str] = None
    publication_date: Optional[str] = None
    version_info: Optional[str] = None
    page_count: Optional[int] = None
    ingested_at: Optional[datetime] = None


# ── Ingestion ────────────────────────────────────────────────

class IngestRequest(BaseModel):
    directory: Optional[str] = Field(
        None, description="Override regulations directory path"
    )


class IngestResult(BaseModel):
    documents_processed: int = 0
    chunks_created: int = 0
    chunks_skipped: int = 0
    errors: list[str] = Field(default_factory=list)


# ── Search ───────────────────────────────────────────────────

class SearchRequest(BaseModel):
    query: str = Field(..., min_length=3, description="Natural-language question")
    top_k: int = Field(5, ge=1, le=20)
    document_id: Optional[UUID] = None


class ChunkResult(BaseModel):
    chunk_id: UUID
    document_id: UUID
    doc_filename: str
    doc_title: Optional[str] = None
    chunk_index: int
    content: str
    page_start: Optional[int] = None
    page_end: Optional[int] = None
    section_title: Optional[str] = None
    similarity: float


class SearchResponse(BaseModel):
    query: str
    results: list[ChunkResult]
    total: int


# ── Compliance ───────────────────────────────────────────────

class ComplianceRequest(BaseModel):
    question: str = Field(
        ..., min_length=5,
        description="Regulatory compliance question or requirement"
    )
    company_evidence: str = Field(
        ..., min_length=5,
        description="Company policy, procedure, or audit evidence text"
    )
    facility_description: Optional[str] = None
    compliance_area: Optional[str] = None
    top_k: int = Field(5, ge=1, le=20)


class RegulatorySource(BaseModel):
    document_name: str
    page_start: Optional[int] = None
    page_end: Optional[int] = None
    section: Optional[str] = None
    excerpt: str
    similarity: Optional[float] = None


class ComplianceFinding(BaseModel):
    requirement: str
    status: str = Field(
        ...,
        description="COMPLIANT | PARTIALLY_COMPLIANT | MISSING_EVIDENCE | POTENTIALLY_NON_COMPLIANT | NEEDS_REVIEW",
    )
    explanation: str
    evidence_found: list[str] = Field(default_factory=list)
    evidence_missing: list[str] = Field(default_factory=list)
    recommended_actions: list[str] = Field(default_factory=list)
    regulatory_sources: list[RegulatorySource] = Field(default_factory=list)


class ComplianceResponse(BaseModel):
    question: str
    overall_status: str
    summary: str
    findings: list[ComplianceFinding] = Field(default_factory=list)
    disclaimer: str = (
        "This analysis is generated by an AI system for informational purposes only. "
        "It does not constitute legal advice, official certification, or a regulatory determination. "
        "Consult qualified regulatory professionals for formal compliance decisions."
    )
    retrieved_sources: list[RegulatorySource] = Field(default_factory=list)


# ── Health ───────────────────────────────────────────────────

class HealthResponse(BaseModel):
    status: str
    database: Optional[dict] = None
    llm_provider: str = "groq"
    embedding_provider: str = "fastembed"
    groq_configured: bool = False
    openai_configured: bool = False
    regulations_dir_exists: bool = False
    pdf_count: int = 0
